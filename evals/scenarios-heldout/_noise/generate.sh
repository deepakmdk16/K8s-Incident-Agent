#!/usr/bin/env bash
# generate.sh — deterministic generator for the held-out root's noise pack.
#
# Same shape as the v2 pack (evals/scenarios-v2/_noise/generate.sh): healthy
# filler namespaces that settle fast under inject.sh's `condition=Available`
# wait, plus decoys that are genuinely, visibly broken and irrelevant to any
# paged symptom. Every name is NEW — the held-out set's point is that nothing
# learned on the frozen set transfers by surface form, and T3 fixtures carry
# every noise name — and the domain is the freight-logistics company the
# held-out cases live in.
#
# Emits, next to itself:
#   noise.yaml      20 healthy filler namespaces (Namespace + ConfigMap +
#                   Deployment on node-cached busybox:1.36 + ClusterIP Service)
#                   and 2 decoy namespaces.
#   namespaces.txt  the WAIT LIST: healthy namespaces only (a decoy is by
#                   construction never Available; the scenario's wait.sh gates
#                   on the decoys instead).
#   decoys.txt      the decoy namespaces, for the scenario wait.sh and review.
#
# Pure function of the static tables below — no $RANDOM, no dates, no host
# state — so reruns are byte-identical. Committed output IS the artifact.
#
# Authoring rules honored (evals/scenarios/README.md):
#   rule 1  EVERY container command, decoys included, succeeds as written once
#           its misconfiguration is corrected — no unconditional `exit 1`;
#   rule 3  only node-cached busybox:1.36; the unschedulable decoy uses
#           cpu: "512", which no real host satisfies;
#   rule 4  names encode product/infra function, never mechanism;
#   no namespace collides with a case-owned one (cold-chain, dispatch,
#   customs-docs, yard-ops, driver-portal) or with any name in the frozen or
#   v2 roots.
set -eu
cd "$(dirname "$0")"

# namespace  deployment  container   (single-space separated)
ROWS="\
load-board load-matcher matcher
rate-quotes quote-builder builder
hos-compliance hos-auditor auditor
weigh-station scale-ingest ingest
dock-scheduling dock-planner planner
carrier-onboarding carrier-vetting vetting
claims-desk claims-intake intake
pallet-tracking pallet-scanner scanner
route-weather weather-feed feed
eld-sync eld-harvester harvester
tire-telemetry tire-pressure-hub hub
dvir-reports dvir-archiver archiver
lane-pricing lane-rater rater
port-gate gate-appointments appointments
rail-interchange rail-handoff handoff
broker-portal broker-console console
shipment-events event-fanout fanout
geofence-alerts geofence-evaluator evaluator
cargo-insurance coverage-checker checker
fleet-cards card-authorizer authorizer"

# 2-3 plausible settings per namespace, two-space indented for the ConfigMap
# data block.
cm_data() {
  case "$1" in
    load-board)
      printf '  refresh_seconds: "20"\n  max_open_loads: "5000"\n' ;;
    rate-quotes)
      printf '  fuel_surcharge_percent: "18.5"\n  quote_ttl_minutes: "30"\n' ;;
    hos-compliance)
      printf '  drive_limit_hours: "11"\n  cycle_days: "8"\n  warn_minutes_before: "30"\n' ;;
    weigh-station)
      printf '  scale_poll_ms: "500"\n  gross_limit_lbs: "80000"\n' ;;
    dock-scheduling)
      printf '  slot_minutes: "30"\n  doors_per_site: "24"\n  overbook_percent: "5"\n' ;;
    carrier-onboarding)
      printf '  insurance_minimum_usd: "1000000"\n  mc_lookup_url: "http://authority-lookup.internal:8080"\n' ;;
    claims-desk)
      printf '  auto_approve_under_usd: "250"\n  sla_hours: "72"\n' ;;
    pallet-tracking)
      printf '  tag_protocol: "rfid-gen2"\n  scan_dedupe_seconds: "5"\n' ;;
    route-weather)
      printf '  provider: "nws"\n  refresh_minutes: "15"\n  alert_radius_miles: "25"\n' ;;
    eld-sync)
      printf '  vendor_feeds: "omnitracs,samsara,motive"\n  batch_size: "200"\n' ;;
    tire-telemetry)
      printf '  low_pressure_psi: "85"\n  sample_seconds: "60"\n' ;;
    dvir-reports)
      printf '  retention_months: "36"\n  archive_bucket: "dvir-archive"\n' ;;
    lane-pricing)
      printf '  base_rate_per_mile: "2.15"\n  deadhead_factor: "0.6"\n' ;;
    port-gate)
      printf '  appointment_window_minutes: "60"\n  terminals: "t18,t30,t46"\n' ;;
    rail-interchange)
      printf '  handoff_grace_hours: "4"\n  edi_version: "004010"\n' ;;
    broker-portal)
      printf '  session_minutes: "45"\n  tender_expiry_hours: "2"\n' ;;
    shipment-events)
      printf '  topic: "shipment.status"\n  fanout_workers: "4"\n' ;;
    geofence-alerts)
      printf '  dwell_alert_minutes: "90"\n  fence_buffer_meters: "150"\n' ;;
    cargo-insurance)
      printf '  default_coverage_usd: "100000"\n  hazmat_multiplier: "2.5"\n' ;;
    fleet-cards)
      printf '  daily_fuel_limit_usd: "1200"\n  pin_required: "true"\n' ;;
    *)
      echo "generate.sh: no settings for namespace '$1'" >&2
      exit 1 ;;
  esac
}

printf '%s\n' "# noise.yaml — generated by generate.sh; do not edit by hand." \
  "# Held-out pack: 20 healthy filler namespaces for T3 captures (applied by" \
  "# evals/inject.sh, which then waits for every deployment in namespaces.txt" \
  "# to be Available) plus 2 deliberately broken, entirely irrelevant decoys." >noise.yaml
: >namespaces.txt
: >decoys.txt

printf '%s\n' "$ROWS" | while read -r NS DEP CTR; do
  [ -n "$NS" ] || continue
  printf '%s\n' "$NS" >>namespaces.txt
  cat >>noise.yaml <<EOF
---
apiVersion: v1
kind: Namespace
metadata:
  name: $NS
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: $DEP-settings
  namespace: $NS
data:
$(cm_data "$NS")
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: $DEP
  namespace: $NS
  labels:
    app: $DEP
spec:
  replicas: 1
  selector:
    matchLabels:
      app: $DEP
  template:
    metadata:
      labels:
        app: $DEP
    spec:
      containers:
        - name: $CTR
          image: busybox:1.36
          imagePullPolicy: IfNotPresent
          command:
            - sh
            - -c
            - echo '$DEP up'; exec sleep 2147483647
          resources:
            requests:
              cpu: 10m
              memory: 16Mi
---
apiVersion: v1
kind: Service
metadata:
  name: $DEP
  namespace: $NS
spec:
  type: ClusterIP
  selector:
    app: $DEP
  ports:
    - name: http
      port: 8080
      targetPort: 8080
EOF
done

emit_decoy_header() {
  cat >>noise.yaml <<EOF
---
apiVersion: v1
kind: Namespace
metadata:
  name: $1
EOF
  printf '%s\n' "$1" >>decoys.txt
}

# DECOY 1 — a trailer-pool rebalancer that can never be scheduled. Same shape
# as a real pod-unschedulable fault; conditional, so a satisfiable request
# fixes it.
emit_decoy_header trailer-pool
cat >>noise.yaml <<'EOF'
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: pool-balancer
  namespace: trailer-pool
  labels:
    app: pool-balancer
spec:
  replicas: 1
  selector:
    matchLabels:
      app: pool-balancer
  template:
    metadata:
      labels:
        app: pool-balancer
    spec:
      containers:
        - name: balancer
          image: busybox:1.36
          imagePullPolicy: IfNotPresent
          command:
            - sh
            - -c
            - echo 'pool-balancer up'; exec sleep 2147483647
          resources:
            requests:
              cpu: "512"
              memory: 64Mi
EOF

# DECOY 2 — a quarterly fuel-tax filer whose jurisdiction table was never
# mounted. Leaves Failed jobs and Warning events; conditional, so mounting the
# file fixes the job.
emit_decoy_header fuel-tax
cat >>noise.yaml <<'EOF'
---
apiVersion: batch/v1
kind: CronJob
metadata:
  name: ifta-filer
  namespace: fuel-tax
spec:
  schedule: "*/1 * * * *"
  concurrencyPolicy: Forbid
  startingDeadlineSeconds: 30
  successfulJobsHistoryLimit: 0
  failedJobsHistoryLimit: 1
  jobTemplate:
    spec:
      backoffLimit: 1
      template:
        spec:
          restartPolicy: Never
          containers:
            - name: filer
              image: busybox:1.36
              imagePullPolicy: IfNotPresent
              command:
                - sh
                - -c
                - |
                  if [ ! -f /filings/jurisdictions.csv ]; then
                    echo "ifta-filer: /filings/jurisdictions.csv is missing"
                    exit 1
                  fi
                  echo "ifta-filer: filing $(wc -l < /filings/jurisdictions.csv) jurisdictions"
              volumeMounts:
                - name: filings
                  mountPath: /filings
              resources:
                requests:
                  cpu: 10m
                  memory: 16Mi
          volumes:
            - name: filings
              emptyDir: {}
EOF

echo "generate.sh: wrote noise.yaml ($(grep -c '^kind: Namespace$' noise.yaml) namespaces:" \
     "$(wc -l <namespaces.txt | tr -d ' ') healthy + $(wc -l <decoys.txt | tr -d ' ') decoys)"
