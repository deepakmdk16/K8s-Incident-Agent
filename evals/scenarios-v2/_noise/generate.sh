#!/usr/bin/env bash
# generate.sh — deterministic generator for the v2 noise pack.
#
# The frozen pack (evals/scenarios/_noise/) is ALL HEALTHY, which hands every
# T3 case a giveaway: the only broken object in the cluster is the answer.
# This pack keeps those 20 healthy namespaces byte-for-byte and adds three
# workloads that are genuinely, visibly broken and completely irrelevant to any
# paged symptom, so triage has to reject plausible decoys instead of homing on
# the single unhealthy thing.
#
# Emits, next to itself:
#   noise.yaml      the 20 healthy filler namespaces + 3 decoy namespaces.
#   namespaces.txt  the WAIT LIST: healthy namespaces only. inject.sh blocks on
#                   `condition=Available` for every namespace named here, and a
#                   decoy is by construction never Available — the scenario's
#                   own wait.sh gates on the decoys instead.
#   decoys.txt      the decoy namespaces, for the scenario wait.sh and review.
#
# Pure function of the static tables below — no $RANDOM, no dates, no host
# state — so reruns are byte-identical.
#
# Authoring rules honored (evals/scenarios/README.md):
#   rule 1  EVERY container command, decoys included, succeeds as written once
#           its misconfiguration is corrected — no unconditional `exit 1`;
#   rule 3  only node-cached busybox:1.36; the unschedulable decoy uses
#           cpu: "512", which no real host satisfies;
#   rule 4  names encode product/infra function, never mechanism (these names
#           are agent-visible in T3 fixtures);
#   no namespace collides with a scenario-owned one (payments, storefront, web,
#   recs, fraud, analytics, shop, orders, checkout, inventory, billing, search,
#   analytics-batch).
set -eu
cd "$(dirname "$0")"

FROZEN=../../scenarios/_noise
[ -f "$FROZEN/noise.yaml" ] || { echo "generate.sh: missing $FROZEN/noise.yaml" >&2; exit 1; }

# --- healthy filler: reuse the frozen pack verbatim rather than restating it.
# Copying the committed artifact (not re-deriving it) is what guarantees the
# healthy half of this pack is identical to the one the frozen T3 cases were
# captured against, so a score change can only come from the decoys.
{
  printf '%s\n' \
    "# noise.yaml — generated by generate.sh; do not edit by hand." \
    "# v2 pack: the frozen 20 healthy filler namespaces (copied verbatim from" \
    "# evals/scenarios/_noise/noise.yaml) plus 3 deliberately broken, entirely" \
    "# irrelevant decoy workloads. See generate.sh for the contract."
  tail -n +4 "$FROZEN/noise.yaml"
} >noise.yaml
cp "$FROZEN/namespaces.txt" namespaces.txt

# --- decoys: namespace deployment container
: >decoys.txt

emit_decoy_header() {
  cat >>noise.yaml <<EOF
---
apiVersion: v1
kind: Namespace
metadata:
  name: $1
EOF
  printf '%s\n' "$1" >>decoys.txt
}

# DECOY 1 — a canary that crashloops because its target is unset. Same shape as
# a real app-crashloop fault; conditional, so setting CANARY_TARGET_URL fixes it.
emit_decoy_header release-canary
cat >>noise.yaml <<'EOF'
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: canary-runner
  namespace: release-canary
  labels:
    app: canary-runner
spec:
  replicas: 1
  selector:
    matchLabels:
      app: canary-runner
  template:
    metadata:
      labels:
        app: canary-runner
    spec:
      containers:
        - name: runner
          image: busybox:1.36
          imagePullPolicy: IfNotPresent
          command:
            - sh
            - -c
            - |
              if [ -z "${CANARY_TARGET_URL:-}" ]; then
                echo "canary-runner: CANARY_TARGET_URL is not set, cannot start"
                exit 1
              fi
              echo "canary-runner: polling ${CANARY_TARGET_URL}"
              exec sleep 2147483647
          resources:
            requests:
              cpu: 10m
              memory: 16Mi
EOF

# DECOY 2 — a nightly export whose destination file was never mounted. Leaves
# Failed jobs and Warning events; conditional, so mounting it fixes the job.
emit_decoy_header report-exports
cat >>noise.yaml <<'EOF'
---
apiVersion: batch/v1
kind: CronJob
metadata:
  name: nightly-export
  namespace: report-exports
spec:
  schedule: "*/1 * * * *"
  concurrencyPolicy: Forbid
  startingDeadlineSeconds: 30
  successfulJobsHistoryLimit: 0
  failedJobsHistoryLimit: 1
  jobTemplate:
    spec:
      backoffLimit: 1
      template:
        spec:
          restartPolicy: Never
          containers:
            - name: exporter
              image: busybox:1.36
              imagePullPolicy: IfNotPresent
              command:
                - sh
                - -c
                - |
                  if [ ! -f /export/destination.conf ]; then
                    echo "nightly-export: /export/destination.conf is missing"
                    exit 1
                  fi
                  echo "nightly-export: uploading to $(cat /export/destination.conf)"
              volumeMounts:
                - name: export-target
                  mountPath: /export
              resources:
                requests:
                  cpu: 10m
                  memory: 16Mi
          volumes:
            - name: export-target
              emptyDir: {}
EOF

# DECOY 3 — a trainer that can never be scheduled. Same shape as a real
# pod-unschedulable fault; conditional, so a satisfiable request fixes it.
emit_decoy_header batch-compute
cat >>noise.yaml <<'EOF'
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: model-trainer
  namespace: batch-compute
  labels:
    app: model-trainer
spec:
  replicas: 1
  selector:
    matchLabels:
      app: model-trainer
  template:
    metadata:
      labels:
        app: model-trainer
    spec:
      containers:
        - name: trainer
          image: busybox:1.36
          imagePullPolicy: IfNotPresent
          command:
            - sh
            - -c
            - echo 'model-trainer started'; exec sleep 2147483647
          resources:
            requests:
              cpu: "512"
              memory: 64Mi
EOF

echo "generate.sh: wrote noise.yaml ($(grep -c '^kind: Namespace$' noise.yaml) namespaces:" \
     "$(wc -l <namespaces.txt | tr -d ' ') healthy + $(wc -l <decoys.txt | tr -d ' ') decoys)"
