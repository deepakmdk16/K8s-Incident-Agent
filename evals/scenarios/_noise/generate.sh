#!/usr/bin/env bash
# generate.sh — deterministic generator for the T3 noise pack.
#
# Emits, next to itself:
#   noise.yaml      20 healthy filler namespaces, each: Namespace + ConfigMap
#                   + Deployment (1 replica, node-cached busybox:1.36, plain
#                   long-sleep, requests 10m/16Mi, no probes) + ClusterIP
#                   Service (8080). Healthy-by-design so inject.sh's
#                   `kubectl wait --for=condition=Available` settles fast.
#   namespaces.txt  exactly the namespaces created, one per line (inject.sh
#                   iterates this to wait per namespace).
#
# Pure function of the static table below — no $RANDOM, no dates, no host
# state — so reruns are byte-identical. Committed output IS the artifact;
# rerun only to regenerate after editing the table.
#
# Authoring rules honored (evals/scenarios/README.md):
#   rule 1  every container command succeeds as written (no injected fault);
#   rule 3  only the node-cached busybox:1.36, values trivially schedulable;
#   rule 4  namespaced objects + Namespaces only; names encode product/infra
#           function, never mechanism or filler vocabulary (these names are
#           agent-visible in T3 fixtures);
#   no namespace collides with any scenario-owned namespace (payments, web,
#   recs, fraud, analytics, shop, orders, checkout, inventory, billing,
#   search, analytics-batch).
set -eu
cd "$(dirname "$0")"

# namespace  deployment  container   (single-space separated)
ROWS="\
platform-metrics metrics-collector collector
log-aggregation log-shipper shipper
message-broker queue-server server
user-profiles profile-api api
cdn-edge edge-cache cache
ab-testing experiment-api api
email-delivery smtp-relay relay
session-store session-cache cache
feature-flags flag-server server
geo-routing geoip-api api
push-notifications push-dispatcher dispatcher
asset-pipeline thumbnailer worker
distributed-tracing span-collector collector
internal-dns dns-forwarder forwarder
loyalty-points points-engine engine
pricing-sync price-worker worker
media-transcode transcode-worker worker
partner-api partner-gateway gateway
webhooks webhook-relay relay
currency-rates rates-fetcher fetcher"

# 2-3 plausible config keys per namespace, two-space indented for the
# ConfigMap data block.
cm_data() {
  case "$1" in
    platform-metrics)
      printf '  scrape_interval_seconds: "15"\n  retention_days: "7"\n' ;;
    log-aggregation)
      printf '  flush_interval_seconds: "30"\n  buffer_size_mb: "8"\n  log_level: "info"\n' ;;
    message-broker)
      printf '  listen_port: "5672"\n  max_connections: "256"\n' ;;
    user-profiles)
      printf '  db_host: "profiles-db.user-profiles.svc"\n  cache_ttl_seconds: "300"\n' ;;
    cdn-edge)
      printf '  origin_host: "assets.internal"\n  cache_ttl_seconds: "600"\n  gzip_enabled: "true"\n' ;;
    ab-testing)
      printf '  default_variant: "control"\n  sample_percent: "10"\n' ;;
    email-delivery)
      printf '  smtp_host: "smtp.internal"\n  from_address: "no-reply@example.com"\n  retry_count: "3"\n' ;;
    session-store)
      printf '  listen_port: "6379"\n  eviction_policy: "lru"\n  max_entries: "10000"\n' ;;
    feature-flags)
      printf '  refresh_interval_seconds: "60"\n  default_state: "off"\n' ;;
    geo-routing)
      printf '  database_path: "/data/geoip.mmdb"\n  reload_hours: "24"\n' ;;
    push-notifications)
      printf '  batch_size: "100"\n  delivery_timeout_seconds: "10"\n' ;;
    asset-pipeline)
      printf '  output_format: "webp"\n  quality: "82"\n  worker_threads: "2"\n' ;;
    distributed-tracing)
      printf '  sample_rate: "0.01"\n  collector_port: "9411"\n' ;;
    internal-dns)
      printf '  upstream_server: "10.96.0.10"\n  cache_size: "1024"\n' ;;
    loyalty-points)
      printf '  earn_ratio: "0.05"\n  redeem_minimum: "500"\n' ;;
    pricing-sync)
      printf '  sync_interval_minutes: "15"\n  source_feed: "vendor-a"\n' ;;
    media-transcode)
      printf '  preset: "h264-720p"\n  segment_seconds: "6"\n' ;;
    partner-api)
      printf '  listen_port: "8080"\n  cors_origins: "*.partner.example.com"\n' ;;
    webhooks)
      printf '  retry_count: "5"\n  timeout_seconds: "8"\n' ;;
    currency-rates)
      printf '  base_currency: "USD"\n  refresh_minutes: "30"\n' ;;
    *)
      echo "generate.sh: no config data for namespace '$1'" >&2
      exit 1 ;;
  esac
}

printf '%s\n' "# noise.yaml — generated by generate.sh; do not edit by hand." \
  "# 20 healthy filler namespaces for T3 captures (applied by evals/inject.sh," \
  "# which then waits for every deployment to be Available)." >noise.yaml
: >namespaces.txt

printf '%s\n' "$ROWS" | while read -r NS DEP CTR; do
  [ -n "$NS" ] || continue
  printf '%s\n' "$NS" >>namespaces.txt
  cat >>noise.yaml <<EOF
---
apiVersion: v1
kind: Namespace
metadata:
  name: $NS
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: $DEP-config
  namespace: $NS
data:
$(cm_data "$NS")
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: $DEP
  namespace: $NS
  labels:
    app: $DEP
spec:
  replicas: 1
  selector:
    matchLabels:
      app: $DEP
  template:
    metadata:
      labels:
        app: $DEP
    spec:
      containers:
        - name: $CTR
          image: busybox:1.36
          imagePullPolicy: IfNotPresent
          command:
            - sh
            - -c
            - echo '$DEP started'; exec sleep 2147483647
          resources:
            requests:
              cpu: 10m
              memory: 16Mi
---
apiVersion: v1
kind: Service
metadata:
  name: $DEP
  namespace: $NS
spec:
  type: ClusterIP
  selector:
    app: $DEP
  ports:
    - name: http
      port: 8080
      targetPort: 8080
EOF
done

echo "generate.sh: wrote noise.yaml + namespaces.txt ($(grep -c '^kind: Namespace$' noise.yaml) namespaces)"
